const syncHistoryCopy = {
  en: syncHistoryEnglishCopy,
  zh: syncHistoryChineseCopy,
} as const;

export type SyncHistoryLocale = keyof typeof syncHistoryCopy;

export function resolveSyncHistoryLocale(language?: string): SyncHistoryLocale {
  return language?.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function syncHistoryText(
  locale: SyncHistoryLocale,
  key: SyncHistoryCopyKey,
  values?: Readonly<Record<string, string | number>>,
): string {
  const template = syncHistoryCopy[locale][key];
  if (!values) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}
